/** Прицельный вопрос под искажение, если он есть в карте. */
export function promptForDistortion(distortion: string | null | undefined): string | null {
  return distortion ? (DISTORTION_PROMPTS[distortion] ?? null) : null;
}

/* —————————————————————————————————————————————————————————————————————————————
 * Светлая (positive) арка осмысления — savoring, НЕ препарирование.
 *
 * Светлые состояния по emotion-domain укрепляют — их усиливают, длят и заякоривают, а не
 * оспаривают и не «смягчают». Прогнать радость через «отдели факт → оспорь → смягчи» — это
 * подавление радости руками инструмента (искажение, которое продукт сам помечает вредным).
 * Поэтому для positive — отдельная дуга (зеркало негативной):
 *   что это питало/благодарность (SOURCE) → что это говорит о тебе/ценность (POSITIVE_MEANING)
 *   → что забрать и как вернуть (CARRY).
 * Шаг «побыть в теле/дыхании» не нужен: дыхание и локализация уже прожиты при записи эмоции.
 * Положительное убеждение — ЗАЯКОРИТЬ (ANCHOR_BELIEF), собрать опору под него, а не расшатать
 * (зеркало CORE_BELIEF). Тон — spiritual-voice; основания — Брайант (savoring), Фредриксон
 * (broaden-and-build), positive data log.
 * ————————————————————————————————————————————————————————————————————————————— */

