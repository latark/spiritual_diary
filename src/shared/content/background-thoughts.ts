/**
 * Фоновые мысли (КПТ) — контент шага «фоновая мысль» в записи эмоции.
 * За чувством или ситуацией обычно стоит распространённый «загон»: искажённая
 * автоматическая мысль. Каждая запись — пара: автоматическая мысль (negative) →
 * рациональная переустановка (positive). Подход КПТ, тон тёплый, на «ты», женские формы.
 *
 * Два набора:
 *  - по оттенку эмоции (shadeId, id из emotions.ts) — 44 оттенка × 2;
 *  - по сфере жизни (sphere = чакра) — 7 сфер × 2.
 * Источник правды по текстам — claude_files/«Фоновые мысли — КПТ.md».
 *
 * Не путать с «Установками ума» (mind-attitudes.ts) — то отдельный методичный контент
 * для практики Фазы 5.5.
 *
 * ⚠️ id назначается по порядку появления и хранится в БД (emotion_entries.background_thought_id,
 * диапазон 1..200). НЕ переставляй и не удаляй записи — только дополняй в конец.
 *
 * ⚠️ Канон цветка (claude_files) — 9 семей / 44 оттенка. emotions.ts пока шире (10 семей,
 * включая «Отвращение», и оттенки-центры). Эти 44 привязки используют существующие id
 * emotions.ts; непокрытые оттенки (страх как оттенок, отвращение и т.п.) отрабатываются
 * фолбэком на семью/сферу в ThoughtStep.
 */

import type { LifeSphereId } from './life-spheres';

export interface BackgroundThought {
  id: number;
  /** Автоматическая (искажённая) мысль за чувством/ситуацией. */
  negative: string;
  /** Рациональная переустановка по КПТ. */
  positive: string;
  /** Тип когнитивного искажения (служебно, на экране не показываем). */
  distortion: string;
  /**
   * Убеждение-схема о себе/идентичности («я недостаточна», «я одна»). Прорабатывается не
   * быстрым челленджем, а регистром CORE_BELIEF (downward arrow + самосострадание).
   */
  core?: boolean;
  /** Привязка к оттенку эмоции (id из emotions.ts), если мысль эмоциональная. */
  shadeId?: string;
  /** Привязка к сфере жизни (= чакра), если мысль про сферу. */
  sphere?: LifeSphereId;
}

