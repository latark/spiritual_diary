// id назначается по порядку (эмоции, затем сферы). Контракт стабильности — см. шапку.
function build(): BackgroundThought[] {
  const out: BackgroundThought[] = [];
  let id = 0;
  for (const { shadeId, pairs } of EMOTION_SOURCE) {
    for (const [negative, positive, distortion, core] of pairs) {
      out.push({ id: ++id, negative, positive, distortion, shadeId, ...(core ? { core } : {}) });
    }
  }
  for (const { sphere, pairs } of SPHERE_SOURCE) {
    for (const [negative, positive, distortion, core] of pairs) {
      out.push({ id: ++id, negative, positive, distortion, sphere, ...(core ? { core } : {}) });
    }
  }
  return out;
}

export const BACKGROUND_THOUGHTS: BackgroundThought[] = build();

export const THOUGHT_BY_ID: ReadonlyMap<number, BackgroundThought> = new Map(
  BACKGROUND_THOUGHTS.map((t) => [t.id, t]),
);

function groupBy<K>(key: (t: BackgroundThought) => K | undefined): Map<K, BackgroundThought[]> {
  const map = new Map<K, BackgroundThought[]>();
  for (const t of BACKGROUND_THOUGHTS) {
    const k = key(t);
    if (k === undefined) continue;
    const arr = map.get(k);
    if (arr) arr.push(t);
    else map.set(k, [t]);
  }
  return map;
}

/** Мысли по оттенку эмоции (shadeId из emotions.ts). */
export const THOUGHTS_BY_SHADE: ReadonlyMap<string, BackgroundThought[]> = groupBy(
  (t) => t.shadeId,
);

/** Мысли по сфере жизни (= чакра). */
export const THOUGHTS_BY_SPHERE: ReadonlyMap<LifeSphereId, BackgroundThought[]> = groupBy(
  (t) => t.sphere,
);

/** Все эмоциональные мысли семьи (по префиксу shadeId), для фолбэка/«показать все». */
export function thoughtsByFamily(familyId: string): BackgroundThought[] {
  const prefix = `${familyId}_`;
  return BACKGROUND_THOUGHTS.filter((t) => t.shadeId?.startsWith(prefix));
}
