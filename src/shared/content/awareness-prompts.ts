/**
 * Вопросы для проработки записи. Пустой лист тянет к пересказу; вопрос-приглашение
 * помогает увидеть причину реакции и переосмыслить мысль. Тон — голос проводника (на «ты»,
 * приглашение). Это НЕ кризисные тексты: острое состояние ведёт отдельный pipeline (§6).
 *
 * КРИТЕРИИ любого вопроса здесь (нарушение = промах по доверию уязвимой аудитории):
 *  1. content-open — работает, не зная деталей ситуации, и зовёт принести своё. НЕ
 *     presupposing: никаких «если бы это сделал…» / «ты же сказала…», что достраивают
 *     сценарий, которого не было.
 *  2. сначала собрать, потом отражать — порядок thought record. На «Пути → Инсайт»
 *     первичный контекст (ситуация, эмоция, мысль) уже собран при записи, поэтому здесь —
 *     только углубление: отделить факт от интерпретации → разобраться → понять себя → своя версия.
 *  3. признание раньше вызова на тяжёлом.
 *  4. под глубину: поверхностная автомысль → быстрая переустановка; убеждение-схема о себе
 *     (BackgroundThought.core) → CORE_BELIEF (расшатать, не углублять), не челлендж.
 *
 * Наборы — половины КПТ-thought-record. REFLECTION — мягкое осмысление по умолчанию (им же
 * сеется намёк после записи). Остальные питают лестницу проработки «Путь → Инсайт»
 * (InsightLadder), углубляя уже собранное: REENTER (вернуться) → FACT (отделить факт от
 * интерпретации) → EXAMINE/DISTORTION (разобраться в ситуации) → SELF (понять себя) →
 * ALTERNATIVE (своя бережная версия). CORE_BELIEF заменяет EXAMINE, когда мысль — схема о себе.
 */

